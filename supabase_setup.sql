-- TraceGate: test history table
create table if not exists public.test_runs (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    run_id integer,
    test_name text,
    prompt text,
    model_a_answer text,
    model_b_answer text,
    model_a_score numeric,
    model_b_score numeric,
    average_score numeric,
    result text,
    created_at timestamptz not null default now()
);

-- Enable row-level security
alter table public.test_runs enable row level security;

-- Users can read only their own test results
create policy "Users can read their own test runs"
on public.test_runs
for select
to authenticated
using (auth.uid() = user_id);

-- Users can add test results only for themselves
create policy "Users can insert their own test runs"
on public.test_runs
for insert
to authenticated
with check (auth.uid() = user_id);
